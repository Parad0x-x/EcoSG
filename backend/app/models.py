"""SQLAlchemy ORM models + Pydantic schemas for ECOSG.

Three tables model the "financial data architecture":
  - Company: identity/sector reference data
  - FinancialMetric: return/valuation data (the "financial returns" side)
  - EsgComponent: raw Environmental / Social / Governance sub-scores
    (the "ESG accountability" side, before weighting/normalization)

The scoring framework (see scoring.py) reads EsgComponent rows and
produces the derived composite ESGScore -- it is not stored, it's
computed on read, so changing the methodology never requires a
data migration.
"""
from __future__ import annotations

import datetime

from sqlalchemy import Float, ForeignKey, Integer, String, Date
from sqlalchemy.orm import Mapped, mapped_column, relationship
from pydantic import BaseModel, ConfigDict, Field

from .database import Base


# ---------------------------------------------------------------------------
# ORM models
# ---------------------------------------------------------------------------

class Company(Base):
    __tablename__ = "companies"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    ticker: Mapped[str] = mapped_column(String(10), unique=True, index=True)
    name: Mapped[str] = mapped_column(String(120))
    sector: Mapped[str] = mapped_column(String(60), index=True)

    financials: Mapped["FinancialMetric"] = relationship(
        back_populates="company", uselist=False, cascade="all, delete-orphan"
    )
    esg: Mapped["EsgComponent"] = relationship(
        back_populates="company", uselist=False, cascade="all, delete-orphan"
    )
    controversies: Mapped[list["ControversyEvent"]] = relationship(
        back_populates="company", cascade="all, delete-orphan"
    )
    factor_fundamentals: Mapped["FactorFundamentals"] = relationship(
        back_populates="company", uselist=False, cascade="all, delete-orphan"
    )
    price_points: Mapped[list["PricePoint"]] = relationship(
        back_populates="company", cascade="all, delete-orphan"
    )


class FinancialMetric(Base):
    __tablename__ = "financial_metrics"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    company_id: Mapped[int] = mapped_column(ForeignKey("companies.id"), unique=True)

    price: Mapped[float] = mapped_column(Float)
    market_cap_b: Mapped[float] = mapped_column(Float)  # billions USD
    one_year_return_pct: Mapped[float] = mapped_column(Float)
    three_year_annualized_return_pct: Mapped[float] = mapped_column(Float)
    volatility_pct: Mapped[float] = mapped_column(Float)  # annualized stdev

    company: Mapped["Company"] = relationship(back_populates="financials")


class EsgComponent(Base):
    __tablename__ = "esg_components"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    company_id: Mapped[int] = mapped_column(ForeignKey("companies.id"), unique=True)

    # Raw sub-scores, 0-100, higher is better, as reported/derived from
    # (mocked) disclosures. In production these would be assembled from
    # many underlying data points per pillar -- here each is a single
    # representative mock figure.
    environmental_score: Mapped[float] = mapped_column(Float)
    social_score: Mapped[float] = mapped_column(Float)
    governance_score: Mapped[float] = mapped_column(Float)

    # Confidence inputs: share of inputs the company reports, and the
    # (simulated) standard deviation of pillar scores across raters.
    data_coverage_pct: Mapped[float] = mapped_column(Float)
    rater_spread: Mapped[float] = mapped_column(Float)

    # Pillar scores one year earlier, for the trend signal.
    env_prev: Mapped[float] = mapped_column(Float)
    social_prev: Mapped[float] = mapped_column(Float)
    gov_prev: Mapped[float] = mapped_column(Float)

    company: Mapped["Company"] = relationship(back_populates="esg")


class ControversyEvent(Base):
    """One dated controversy. The penalty is derived on read (scoring.py),
    so it decays with time without any data migration."""
    __tablename__ = "controversy_events"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    company_id: Mapped[int] = mapped_column(ForeignKey("companies.id"), index=True)
    category: Mapped[int] = mapped_column(Integer)  # 1 low .. 5 severe
    occurred_on: Mapped[datetime.date] = mapped_column(Date)
    title: Mapped[str] = mapped_column(String(160))

    company: Mapped["Company"] = relationship(back_populates="controversies")


class FactorFundamentals(Base):
    """Yfinance-`.info`-shaped fundamentals feeding the quant factor model
    (see quant/factors.py). Kept as its own table -- separate from
    FinancialMetric -- because it's a different data domain (raw fields a
    factor model consumes, not the summary stats the ESG side displays),
    generated by quant_seed.py rather than hand-authored."""
    __tablename__ = "factor_fundamentals"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    company_id: Mapped[int] = mapped_column(ForeignKey("companies.id"), unique=True)

    market_cap: Mapped[float] = mapped_column(Float)
    enterprise_value: Mapped[float] = mapped_column(Float)
    trailing_pe: Mapped[float] = mapped_column(Float)
    price_to_book: Mapped[float] = mapped_column(Float)
    return_on_equity: Mapped[float] = mapped_column(Float)
    return_on_assets: Mapped[float] = mapped_column(Float)
    gross_margins: Mapped[float] = mapped_column(Float)
    operating_margins: Mapped[float] = mapped_column(Float)
    profit_margins: Mapped[float] = mapped_column(Float)
    debt_to_equity: Mapped[float] = mapped_column(Float)
    free_cashflow: Mapped[float] = mapped_column(Float)
    ebitda: Mapped[float] = mapped_column(Float)
    revenue_growth: Mapped[float] = mapped_column(Float)
    earnings_growth: Mapped[float] = mapped_column(Float)
    beta: Mapped[float] = mapped_column(Float)
    current_price: Mapped[float] = mapped_column(Float)
    total_revenue: Mapped[float] = mapped_column(Float)
    total_debt: Mapped[float] = mapped_column(Float)
    total_cash: Mapped[float] = mapped_column(Float)

    company: Mapped["Company"] = relationship(back_populates="factor_fundamentals")


class PricePoint(Base):
    """One daily close for one company. ~520 trading days per company,
    synthetic (see quant_seed.generate_price_history), feeding the momentum
    and low-volatility factors plus the backtest engine."""
    __tablename__ = "price_points"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    company_id: Mapped[int] = mapped_column(ForeignKey("companies.id"), index=True)
    date: Mapped[datetime.date] = mapped_column(Date, index=True)
    close: Mapped[float] = mapped_column(Float)

    company: Mapped["Company"] = relationship(back_populates="price_points")


# ---------------------------------------------------------------------------
# Pydantic (API) schemas
# ---------------------------------------------------------------------------

class FinancialMetricOut(BaseModel):
    price: float
    market_cap_b: float
    one_year_return_pct: float
    three_year_annualized_return_pct: float
    volatility_pct: float

    model_config = ConfigDict(from_attributes=True)


class EsgComponentOut(BaseModel):
    environmental_score: float
    social_score: float
    governance_score: float
    data_coverage_pct: float
    rater_spread: float
    env_prev: float
    social_prev: float
    gov_prev: float

    model_config = ConfigDict(from_attributes=True)


class ControversyEventOut(BaseModel):
    category: int = Field(..., description="1 (low) to 5 (severe)")
    occurred_on: datetime.date
    title: str
    age_months: float
    decay_factor: float = Field(..., description="Share of the category's points still counted, 0-1")
    penalty_points: float

    model_config = ConfigDict(from_attributes=True)


class EsgScoreOut(BaseModel):
    """Derived output of the scoring framework -- see scoring.py."""

    composite_score: float = Field(..., description="Final 0-100 score: industry-adjusted minus controversy penalty")
    grade: str = Field(..., description="Letter grade after any cap, e.g. 'A', 'BBB'")
    grade_before_cap: str
    grade_cap_reason: str | None = Field(None, description="Why the grade was capped, or null")
    sector_percentile: float = Field(..., description="Percentile rank within sector, 0-100")
    weighted_pillar_score: float = Field(..., description="Materiality-weighted pillar score before industry adjustment")
    industry_adjusted_score: float = Field(..., description="Weighted score rescaled to the sector benchmark range, 0-100")
    benchmark_low: float
    benchmark_high: float
    environmental_score: float
    social_score: float
    governance_score: float
    controversy_penalty: float
    controversy_events: list[ControversyEventOut]
    confidence: str = Field(..., description="high, medium or low; never blended into the score")
    prior_composite_score: float = Field(..., description="Same algorithm run one year earlier")
    trend: float = Field(..., description="composite_score minus prior_composite_score")
    trend_label: str = Field(..., description="improving, stable or worsening")


class CompanyOut(BaseModel):
    ticker: str
    name: str
    sector: str
    financials: FinancialMetricOut
    esg_raw: EsgComponentOut
    esg_score: EsgScoreOut

    model_config = ConfigDict(from_attributes=True)


class CompanySummaryOut(BaseModel):
    """Lighter-weight shape used by list/dashboard endpoints."""

    ticker: str
    name: str
    sector: str
    one_year_return_pct: float
    composite_score: float
    grade: str

    model_config = ConfigDict(from_attributes=True)


class PortfolioHolding(BaseModel):
    ticker: str
    weight_pct: float = Field(..., gt=0, description="Portfolio weight, percent")


class PortfolioRequest(BaseModel):
    holdings: list[PortfolioHolding]


class PortfolioHoldingResult(BaseModel):
    ticker: str
    name: str
    weight_pct: float
    composite_score: float
    grade: str
    one_year_return_pct: float
    quant_composite_score: float | None = Field(
        None, description="Hedge-fund-style multi-factor (Value/Quality/Momentum/Growth/Low-Vol) "
                           "composite z-score, if the ticker is covered by the quant model."
    )
    quant_percentile: float | None = None


class PortfolioResult(BaseModel):
    weighted_esg_score: float
    weighted_one_year_return_pct: float
    grade: str
    return_esg_gap: float = Field(
        ..., description="Weighted return minus a naive 1:1 mapping of ESG score to return, "
                          "as a rough illustration of the 'returns vs ESG accountability' gap."
    )
    weighted_quant_score: float | None = Field(
        None, description="Weighted average hedge-fund-style factor composite z-score across holdings."
    )
    holdings: list[PortfolioHoldingResult]


