class QuantFactorSummary(BaseModel):
    """Row shape for the ranked factor-scan list."""

    ticker: str
    name: str
    sector: str
    composite_score: float = Field(..., description="Cross-sectional composite z-score")
    percentile: float = Field(..., description="0-100 percentile rank across the covered universe")
    rank: int


class QuantFactorFamilyScores(BaseModel):
    value_score: float | None
    quality_score: float | None
    momentum_score: float | None
    growth_score: float | None
    low_vol_score: float | None


class QuantCompanyOut(BaseModel):
    ticker: str
    name: str
    sector: str
    families: QuantFactorFamilyScores
    composite_score: float
    percentile: float
    rank: int
    raw_metrics: dict[str, float | None] = Field(
        ..., description="Selected raw inputs behind the factor scores, for transparency."
    )


class BacktestMetrics(BaseModel):
    cagr: float | None
    annualized_volatility: float | None
    sharpe_ratio: float | None
    sortino_ratio: float | None
    max_drawdown: float | None
    calmar_ratio: float | None
    beta_vs_benchmark: float | None
    benchmark_cagr: float | None
    excess_cagr_vs_benchmark: float | None
    daily_win_rate: float | None
    total_return: float | None
    equal_weight_cagr: float | None = Field(None, description="CAGR of holding every covered stock in equal weights.")
    mean_ic: float | None = Field(None, description="Mean Spearman IC of scores vs next-period returns.")
    ic_t_stat: float | None = Field(None, description="t-stat of the mean IC; below 3 means unproven.")
    ic_periods: int = Field(0, description="Number of rebalance periods behind the IC.")


class EquityCurvePoint(BaseModel):
    date: str
    portfolio: float
    benchmark: float
    equal_weight: float = 1.0


class BacktestSummary(BaseModel):
    metrics: BacktestMetrics
    equity_curve: list[EquityCurvePoint]
    methodology_note: str
